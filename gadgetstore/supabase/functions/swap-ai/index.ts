import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemPrompt = `You are SwapAI, an intelligent assistant for a gadget swap and trade marketplace in Nigeria. You help users with:

1. **Smart Valuation**: When a user mentions a gadget name + condition, estimate its fair market swap value in Nigerian Naira (₦) with reasoning based on current market trends.

2. **Swap Match Suggestions**: Analyze a user's gadget and suggest what devices they should target for a fair swap, considering brand, condition, and value.

3. **Condition Assessment**: When a user describes their device condition in plain text, assign a condition rating (New / Like New / Good / Fair) with explanation.

4. **Deal Fairness Checker**: When a user asks "I have X, they're offering Y — is this fair?", compare values and give a recommendation.

5. **Negotiation Tips**: Suggest how to negotiate or counter a swap proposal effectively.

6. **Fraud Risk Alerts**: Flag suspicious patterns in listings or deals (too-good-to-be-true prices, vague descriptions, pressure tactics).

Always be helpful, concise, and give values in Naira (₦). Use Nigerian market context for pricing. Format responses with markdown for readability.`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limited, please try again later." }), {
          status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted." }), {
          status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("swap-ai error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
